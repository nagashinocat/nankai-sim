import type { Manifest } from '../data.ts';
import { clear, el } from './dom.ts';

export function renderAbout(root: HTMLElement, manifest: Manifest | null): void {
  clear(root);
  const sources = manifest
    ? el('ul', {}, ...manifest.datasets.map((d) => el('li', {}, d.source, d.url ? [' ', el('a', { href: d.url, target: '_blank', rel: 'noopener noreferrer' }, '（入手元）')] : null)))
    : el('p', {}, '出典一覧を読み込めませんでした。');
  root.append(
    el('h2', {}, 'このアプリについて'),
    el('section', { class: 'card' },
      el('h3', {}, '計算のしくみ'),
      el('p', {}, '内閣府の南海トラフ巨大地震の想定（最大クラス）による、250mごとの震度・液状化の想定を使います。入力された建物の構造と建築年に合う「被害関数」（揺れの強さと全壊・半壊の割合の関係）を当てはめ、自宅の値を出します。周辺1kmは、各マスの建物の構成比で按分した推計棟数の合計です。'),
      el('p', { class: 'strong' }, '津波による被害は、全壊・半壊の割合に含まれていません（津波の想定データはまだ入れていません）。海の近くで強い揺れを感じたら、結果にかかわらず、すぐに高い所へ避難してください。'),
      el('p', {}, '現在は三重県の想定データだけを使っています。それ以外の地域では「この地域はまだ対応していません」と表示します（揺れが小さいという意味ではありません）。'),
      el('p', {}, '自宅の結果は「代表値」と、曲線の読み取りの幅などによる「幅（最小〜最大）」で示します。わからない項目があるときは、幅が広くなります。'),
      el('p', {}, '避難場所までの時間は、直線距離を1.3倍して道のりとみなし、標準1.0m/s・ゆっくり0.5m/sで歩く場合の目安です。実際の道のり・坂・混雑・夜間などは考慮していません。')),
    el('section', { class: 'card' }, el('h3', {}, '出典'),
      el('p', {}, '内閣府 南海トラフの巨大地震モデル・被害想定手法検討会 ほか、次のデータを使っています。'), sources,
      el('p', {}, '地図: 国土地理院（淡色地図）。')),
    el('section', { class: 'card' }, el('h3', {}, '仮定と限界'),
      el('ul', {},
        el('li', {}, '被害関数は内閣府の資料の図から読み取った値で、公式の数表ではありません（読み取り誤差があります）。'),
        el('li', {}, '建物の年代区分は、被害関数の区分と入力の区分とで完全には一致しません。'),
        el('li', {}, '「代表曲線」と「幅」は、区分の違いなどを考慮した目安です。地域全体の推計は代表曲線で計算しています。'),
        el('li', {}, '地盤、建物ごとの状態、前震の影響などは反映していません。これは耐震診断ではありません。'),
        el('li', {}, '津波・火災による被害は含まれていません。'))),
    el('section', { class: 'card' }, el('h3', {}, 'プライバシー'),
      el('p', {}, '住所は、座標に変換するために国土地理院の住所検索（msearch.gsi.go.jp）へ送られます。このアプリ専用のサーバーには送りません。'),
      el('p', {}, '地図を表示するとき、表示している範囲の地図画像を国土地理院（cyberjapandata.gsi.go.jp）から取得します。そのため、国土地理院には表示中のおおよその場所が伝わります。'),
      el('p', {}, '入力した内容は、この端末のブラウザの中で計算します。共有する文面には住所や位置情報を含めません。避難場所への経路リンクには、避難場所の座標だけを載せます。'),
      el('p', {}, '経路リンク（Google マップ）と耐震補助制度の検索リンク（Google 検索）は、押したときだけ Google のページを開きます。経路リンクには避難場所の座標が、検索リンクには市町名が含まれるため、押すと Google にはおおよその場所が伝わります。'),
      el('p', {}, '前回の結果（自宅の結果・周辺の推計・近くの避難場所の名前と距離）は、この端末のブラウザの中にだけ保存します。住所と位置情報（座標）は保存しません。「前回の結果を削除」で消せます。')),
    el('p', {}, el('a', { href: '#', class: 'btn-link' }, '入力画面にもどる')),
  );
}
